"""Collect the numbers the report's figures draw into report/figures/data.js.

Run from the repository root: python3 report/scripts/figure_data.py
Run report/scripts/make_numbers.py and report/scripts/pareto_figure.py first: the result values are read
from the generated tables, so a figure always shows exactly what the tables print, and the timetable
example from report/data/pareto_example.json. Then render with: node report/figures/render.mjs
All evaluation data is AI-written (synthetic), not real students; see the report's Appendix B.
"""
import json
import re
from pathlib import Path

ROOT = Path(__file__).resolve().parents[2]
GENERATED = ROOT / "report/latex/generated"
CELL = re.compile(r"([\d.]+) \(([\d.]+) to ([\d.]+)\)")


def table_rows(name: str) -> list[list[str]]:
    """Body rows of a generated booktabs table, cells stripped of \\textbf."""
    text = (GENERATED / name).read_text()
    body = text.split(r"\midrule", 1)[1].split(r"\bottomrule", 1)[0]
    rows = []
    for line in body.strip().splitlines():
        line = re.sub(r"\\textbf\{([^}]*)\}", r"\1", line).rstrip("\\ ").strip()
        rows.append([cell.strip() for cell in line.split("&")])
    return rows


def interval(cell: str) -> dict | None:
    match = CELL.fullmatch(cell)
    if not match:
        return None
    value, low, high = (float(v) for v in match.groups())
    return {"value": value, "low": low, "high": high, "text": match.group(1)}


def macros(*names: str) -> dict[str, str]:
    """Values of \\newcommand macros in generated/numbers.tex, as the report prints them."""
    text = (GENERATED / "numbers.tex").read_text()
    out = {}
    for name in names:
        match = re.search(r"\\newcommand\{\\" + name + r"\}\{(.*)\}", text)
        out[name] = match.group(1).replace(r"\ensuremath{-}", "\u2212")
    return out


def main() -> None:
    parse = [{"method": row[0], "deployed": "deployed" in row[0], "clauses": interval(row[1]),
              "sentences": interval(row[2])} for row in table_rows("tab_parse.tex")]
    rank = []
    for row in table_rows("tab_rank.tex"):
        if row[0] == "Random":
            rank.append({"method": row[0], "reference": float(row[1])})
        elif interval(row[1]):
            rank.append({"method": row[0], "deployed": "deployed" in row[0], "pairs": interval(row[1])})
    curve = [{"personas": r["personas"], "accuracy": round(r["accuracy"]["mean"] * 100, 1),
              "sd": round(r["accuracy"]["sd"] * 100, 1), "draws": r["draws"]}
             for r in json.loads((ROOT / "llm/rank/output/learning_curve.json").read_text())
             ["curve"]["with_program_pairs"] if r["sample"] == "random"]
    pareto = json.loads((ROOT / "report/data/pareto_example.json").read_text())
    data = {
        "note": "Generated by report/scripts/figure_data.py. Evaluation data is AI-written (synthetic).",
        "parse": parse, "rank": rank, "curve": curve,
        "pareto": pareto["example"], "students": pareto["students"], "front_sizes": pareto["front_sizes"],
        "candidate_min": pareto["candidate_min"],
        "numbers": macros("pDiffKeyC", "pDiffKeyCLo", "pDiffKeyCHi", "pDiffKeyS", "pDiffKeySLo", "pDiffKeySHi",
                          "rDiffEq", "rDiffEqLo", "rDiffEqHi", "sExamS", "sExamC", "sRankExamPersonas", "sRankScored"),
    }
    out = ROOT / "report/figures/data.js"
    out.write_text("// Generated by report/scripts/figure_data.py; do not edit by hand.\n"
                   f"window.DATA = {json.dumps(data, ensure_ascii=False, indent=1)};\n")
    print(f"wrote {out.relative_to(ROOT)}: {len(parse)} parse rows, {len(rank)} rank rows, {len(curve)} curve points")


if __name__ == "__main__":
    main()
