    src = "llm/rank/output/learning_curve.json: curve.with_program_pairs (sample random)"
    m.add("rCurveSixty", pct(sixty["accuracy"]["mean"]), f"{src}, personas 60: accuracy.mean over {sixty['draws']} draws")
    m.add("rCurveMax", pct(most["accuracy"]["mean"]), f"{src}, personas {most['personas']}: accuracy.mean")

    # summary only: llm/rank/output/RESULTS.md:148 ("对 20 份真实候选算一次平均 3.6 毫秒" =
    # "3.6 ms on average for 20 real candidates, features included"); there is no timing log.
