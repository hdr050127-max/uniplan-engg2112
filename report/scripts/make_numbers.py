ROOT = Path(__file__).resolve().parents[2]
OUT = ROOT / "report/latex/generated"
HEADER = "% Generated by report/scripts/make_numbers.py from the raw result files. Do not edit by hand.\n"


# ---------------------------------------------------------------- reading and formatting helpers

def read_json(rel: str):
    return json.loads((ROOT / rel).read_text(encoding="utf-8"))


def read_jsonl(rel: str) -> list[dict]:
    with (ROOT / rel).open(encoding="utf-8") as handle:
        return [json.loads(line) for line in handle if line.strip()]


def read_csv(rel: str) -> list[dict]:
    with (ROOT / rel).open(encoding="utf-8", newline="") as handle:
        return list(csv.DictReader(handle))


def frac(x) -> Fraction:
    """The exact value: a ratio stored as a float is recovered as the small fraction it came from."""
    if isinstance(x, (Fraction, int)):
        return Fraction(x)
    guess = Fraction(x).limit_denominator(10 ** 6)
    return guess if abs(float(guess) - x) < 1e-12 else Fraction(Decimal(repr(x)))


def fixed(x, places: int) -> str:
    """Round half away from zero to `places` decimals; a negative gets a real minus."""
    scaled = frac(x) * 10 ** places
    n = math.floor(abs(scaled) + Fraction(1, 2))
    text = f"{n // 10 ** places}.{n % 10 ** places:0{places}d}" if places else str(n)
    return (r"\ensuremath{-}" if scaled < 0 and n else "") + text


def pct(x) -> str:
    """A share on the 0-1 scale as a percentage with one decimal (no % sign)."""
    return fixed(frac(x) * 100, 1)


def prop(x) -> str:
    """A share on the 0-1 scale with two decimals."""
    return fixed(x, 2)


def count(n: int) -> str:
    return f"{n:,}".replace(",", "{,}")


def whole(share: float, of: int) -> int:
    """The integer count behind a stored share (share * of must be a whole number)."""
    k = round(share * of)
    assert abs(k - share * of) < 1e-6, (share, of)
    return k


def one(rows: list[dict], test) -> dict:
    found = [row for row in rows if test(row)]
    assert len(found) == 1, f"expected one match, found {len(found)}"
    return found[0]


class Macros:
    def __init__(self) -> None:
        self.items: list[tuple[str, str, str]] = []

    def add(self, name: str, value, source: str) -> None:
        assert re.fullmatch(r"[A-Za-z]+", name), name
        assert name not in {n for n, _, _ in self.items}, name
        self.items.append((name, str(value), source))

    def tex(self) -> str:
        lines = [HEADER.rstrip("\n"),
                 "% All test sentences, personas, labels and exams are synthetic (AI-written); no real students."]
        for name, value, source in self.items:
            lines += [f"% {source}", f"\\newcommand{{\\{name}}}{{{value}}}"]
        return "\n".join(lines) + "\n"


