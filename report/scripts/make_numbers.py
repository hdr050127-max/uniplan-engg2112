def parse_bootstrap() -> tuple[dict, dict, dict]:
    """Unrounded 95% intervals from parse_exam_ci.py's own functions; checked against its JSON."""
    spec = importlib.util.spec_from_file_location("parse_exam_ci", ROOT / "report/scripts/parse_exam_ci.py")
    ci = importlib.util.module_from_spec(spec)
    spec.loader.exec_module(ci)
    gold = ci.load(ci.EXAM)
    rows = {name: ci.per_sentence(gold, file) for name, file in ci.METHODS.items()}
    rng = random.Random(ci.SEED)                      # same draws, in the same order, as parse_exam_ci.main()
    every = range(len(gold))
    samples = [[rng.randrange(len(gold)) for _ in every] for _ in range(ci.REPS)]
    boot = {name: [ci.rates(method_rows, picks) for picks in samples] for name, method_rows in rows.items()}

    def interval(values: list[float]) -> list[float]:   # parse_exam_ci.interval without the rounding
        values = sorted(values)
        return [values[int(0.025 * len(values))], values[int(0.975 * len(values)) - 1]]

    methods = {name: {"clause_ci": interval([b[0] for b in boot[name]]),
                      "sentence_ci": interval([b[1] for b in boot[name]])} for name in rows}
    diffs = {f"{a} minus {b}": {"clause_ci": interval([x[0] - y[0] for x, y in zip(boot[a], boot[b])]),
                                "sentence_ci": interval([x[1] - y[1] for x, y in zip(boot[a], boot[b])])}
             for a, b in ci.PAIRS}
    stored = read_json("report/data/parse_exam_ci.json")
    for group, mine in (("methods", methods), ("differences", diffs)):
        for name, values in mine.items():
            for key in ("clause_ci", "sentence_ci"):
                assert [round(v, 4) for v in values[key]] == stored[group][name][key], (name, key)
    points = {name: (sum(r[0] for r in method_rows), sum(r[1] for r in method_rows), sum(r[2] for r in method_rows))
              for name, method_rows in rows.items()}
    return methods, diffs, points


def parse_numbers(m: Macros) -> list[tuple[str, str, str, bool]]:
    results = read_json("llm/parse/output/exam/parse_results.json")
    sentences = sum(bool(r["sentence_id"].strip()) for r in read_csv("llm/parse/exam/exam.csv"))
    methods, diffs, points = parse_bootstrap()
    src = "llm/parse/output/exam/parse_results.json"
    exact, table = {}, []
    for label, model, ci_name, stem in PARSE_METHODS:
        test = one(results, lambda r: r["model"] == model)["test"]
        clauses_right = whole(test["accuracy"], test["n"])
        sentences_right = whole(test["sentence_all_right"], sentences)
        assert points[ci_name] == (clauses_right, test["n"], sentences_right)   # same scores as the saved predictions
        clause, sentence = Fraction(clauses_right, test["n"]), Fraction(sentences_right, sentences)
        exact[stem or model] = (clause, sentence)
        c_lo, c_hi = methods[ci_name]["clause_ci"]
        s_lo, s_hi = methods[ci_name]["sentence_ci"]
        table.append((label, f"{pct(clause)} ({pct(c_lo)} to {pct(c_hi)})",
                      f"{pct(sentence)} ({pct(s_lo)} to {pct(s_hi)})", "deployed" in label))
        if stem:
            where = f'{src}: model == "{model}", test'
            m.add(f"p{stem}C", pct(clause), f"{where}.accuracy = {clauses_right}/{test['n']}")
            m.add(f"p{stem}S", pct(sentence), f"{where}.sentence_all_right = {sentences_right}/{sentences}")
        if stem == "Rtwo":
            ci_src = (f"95% bootstrap (sentences resampled, 10,000 reps, seed 2112) recomputed with "
                      f"report/scripts/parse_exam_ci.py; matches report/data/parse_exam_ci.json methods.\"{ci_name}\"")
            m.add("pRtwoCLo", pct(c_lo), f"{ci_src}.clause_ci[0] (unrounded {c_lo:.6f})")
            m.add("pRtwoCHi", pct(c_hi), f"{ci_src}.clause_ci[1] (unrounded {c_hi:.6f})")
            m.add("pRtwoSLo", pct(s_lo), f"{ci_src}.sentence_ci[0] (unrounded {s_lo:.6f})")
            m.add("pRtwoSHi", pct(s_hi), f"{ci_src}.sentence_ci[1] (unrounded {s_hi:.6f})")

    for stem, other, ci_key in (("One", "Rone", "Qwen 7B QLoRA round 2 minus Qwen 7B QLoRA round 1"),
                                ("Zero", "Zero", "Qwen 7B QLoRA round 2 minus Qwen 7B zero-shot, prompt v2"),
                                ("Key", "Key", "Qwen 7B QLoRA round 2 minus keyword rules")):
        for part, idx, ci_field in (("C", 0, "clause_ci"), ("S", 1, "sentence_ci")):
            diff = exact["Rtwo"][idx] - exact[other][idx]
            lo, hi = diffs[ci_key][ci_field]
            what = "clauses" if part == "C" else "whole sentences"
            m.add(f"pDiff{stem}{part}", pct(diff), f"{src}: round 2 minus p{other}{part} ({what}), exact counts")
            ci_src = f"paired bootstrap recomputed as in report/scripts/parse_exam_ci.py; report/data/parse_exam_ci.json differences.\"{ci_key}\".{ci_field}"
            m.add(f"pDiff{stem}{part}Lo", pct(lo), f"{ci_src}[0] (unrounded {lo:.6f})")
            m.add(f"pDiff{stem}{part}Hi", pct(hi), f"{ci_src}[1] (unrounded {hi:.6f})")

    splits = {whole(one(results, lambda r, mm=mm: r["model"] == mm)["test"]["split_right"], sentences)
              for _, mm, _, _ in PARSE_METHODS}
    assert len(splits) == 1      # splitting is rule-based, so the same for every method
    m.add("pSplit", pct(Fraction(splits.pop(), sentences)), f"{src}: test.split_right (same for every method)")
    return table


