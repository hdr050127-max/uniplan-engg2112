"""Write the report's numbers (LaTeX macros) and Tables 2-4 from the raw result files.

Run from the repository root:  python3 report/scripts/make_numbers.py
Writes report/latex/generated/{numbers,tab_data,tab_parse,tab_rank}.tex. Standard library only,
deterministic, and no model is called: every value is read or recomputed from saved files
(JSON/JSONL/CSV). The few values that exist only in a markdown summary are read with a commented
regex and marked "summary only" in numbers.tex.

Final, citable versions only: parsing and ranking come from the final exams; reasons from the
English explain files (*_en_exam.json). All sentences, personas, labels and exams are synthetic
(AI-written); see report/sources.md.

Formatting: percentages carry one decimal and no % sign (the prose adds \\%); proportions carry two
decimals; both are rounded half away from zero from the exact fraction, not from a rounded copy.
Counts get thousands separators as 1{,}240. Negative numbers use \\ensuremath{-}, a real minus that
also works inside math mode.

The parsing-exam confidence intervals are recomputed from the saved predictions with
report/scripts/parse_exam_ci.py's own functions (same seed and resamples, about 4 s), because
report/data/parse_exam_ci.json stores them rounded to 4 decimals and rounding those again goes
wrong at a boundary (e.g. 0.96746 -> 0.9675 -> 96.8 instead of 96.7). The recomputed values are
checked against that JSON.
"""
