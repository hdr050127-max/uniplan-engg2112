def tab_rows(header: list[str], rows: list[tuple[str, str, str, bool]]) -> str:
    lines = [HEADER.rstrip("\n"), r"{\small", r"\begin{tabular}{@{}lcc@{}}", r"\toprule"]
    lines += [" & ".join(h) + r" \\" for h in header]
    lines.append(r"\midrule")
    for label, a, b, bold in rows:
        cells = [label, a, b]
        if bold:
            cells = [rf"\textbf{{{c}}}" for c in cells]
        lines.append(" & ".join(cells) + r" \\")
    lines += [r"\bottomrule", r"\end{tabular}}"]
    return "\n".join(lines) + "\n"


